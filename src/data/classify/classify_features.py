import pandas as pd
from pathlib import Path

"""
The goal of this script is to create a file that
classifies each column within the master data file
for games.
"""


MASTER_PATH = "data/master/master_game_data.csv"
OUTPUT_PATH = "data/metadata/feature_classification.csv"


# Load data
df = pd.read_csv(MASTER_PATH)

print(f"Loaded dataset: {df.shape[0]:,} rows x {df.shape[1]} columns")

# Feature classification rules

# Columns that identify a game/team/row rather than describe
# something that should be used as a model feature.
IDENTIFIER_COLUMNS = {
    "Unnamed: 0",
    "id",
    "gameId",
    "teamId",
}


# Information that is known before the game begins.
STATIC_PREGAME_COLUMNS = {
    "isHome",
    "isAway",
    "homeAway",
    "seasonType",
    "startDate",
}


# Game Metadata
METADATA_COLUMNS = {
    "season",
    "week",
    "conference",
    "team",
    "homeTeam",
    "awayTeam",
    "opponent",
    "completed",
}


# Current-game outcome/statistic columns.

# These are NOT automatically "targets."
# A particular model may choose one of these as its target.

# They are classified separately because they are generated by
# the current game and therefore cannot be used as inputs to a
# pregame predictive model.
CURRENT_GAME_COLUMNS = {
    # Scoring / outcomes
    "points",
    "homePoints",
    "awayPoints",
    "pointsFor",
    "pointsAgainst",
    "pointDifferential",
    "win",

    # Scoring statistics
    "rushingTDs",
    "passingTDs",
    "puntReturnTDs",
    "kickReturnTDs",
    "interceptionTDs",
    "defensiveTDs",
    "kickingPoints",

    # Rushing
    "rushingAttempts",
    "rushingYards",
    "yardsPerRushAttempt",

    # Passing
    "passAttempts",
    "completions",
    "completionAttempts",
    "completionPct",
    "netPassingYards",
    "yardsPerPass",

    # First / third / fourth down
    "firstDowns",
    "thirdDownConversions",
    "thirdDownAttempts",
    "thirdDownPct",
    "thirdDownEff",
    "fourthDownConversions",
    "fourthDownAttempts",
    "fourthDownPct",
    "fourthDownEff",

    # Turnovers / fumbles
    "fumblesRecovered",
    "fumblesLost",
    "totalFumbles",
    "interceptions",
    "passesIntercepted",
    "turnovers",

    # Returns
    "puntReturnYards",
    "puntReturns",
    "kickReturnYards",
    "kickReturns",
    "interceptionYards",

    # Penalties
    "penalties",
    "penaltyYards",
    "totalPenaltiesYards",

    # Possession
    "possessionTime",
    "possessionSeconds",

    # Defense
    "tacklesForLoss",
    "tackles",
    "sacks",
    "qbHurries",
    "passesDeflected",

    # Other game statistics
    "totalYards",
}


# Explicit rolling historical features.
# These represent previous games and therefore can be legitimate
# pregame predictive features.
ROLLING_SUFFIXES = (
    "Last3",
    "Last5",
)


# Explicit indicators that a statistic was calculated using
# information available before the current game.
PREGAME_KEYWORDS = (
    "Before",
    "Pregame",
)

# Classification function

def classify_feature(column):
    """
    Classify a feature based on its name and known role.

    Returns:
        category
        predictive_safe
        target_candidate
        leakage_risk
        reason
    """

    # Identifier

    if column in IDENTIFIER_COLUMNS:
        return (
            "identifier",
            False,
            False,
            "low",
            "Identifier or dataset index"
        )

    # Static pregame information

    if column in STATIC_PREGAME_COLUMNS:
        return (
            "static_pregame",
            True,
            False,
            "low",
            "Information known before kickoff"
        )

    # Metadata
    if column in METADATA_COLUMNS:
        return (
            "metadata",
            False,
            False,
            "low",
            "Descriptive or contextual information about the game/team"
        )

    # Rolling pregame statistics

    if any(column.endswith(suffix) for suffix in ROLLING_SUFFIXES):
        return (
            "rolling_pregame",
            True,
            False,
            "low",
            "Rolling statistic based on previous games"
        )

    # Explicit cumulative / pregame statistics

    if any(keyword in column for keyword in PREGAME_KEYWORDS):
        return (
            "pregame",
            True,
            False,
            "low",
            "Historical statistic calculated before the current game"
        )

    # Current-game statistics

    if column in CURRENT_GAME_COLUMNS:

        # Outcomes are especially likely to be used as targets.
        if column in {
            "win",
            "points",
            "homePoints",
            "awayPoints",
            "pointDifferential",
            "pointsFor",
            "pointsAgainst",
        }:
            return (
                "target_candidate",
                False,
                True,
                "high",
                "Current-game outcome that may be used as a model target"
            )

        return (
            "current_game",
            False,
            False,
            "high",
            "Statistic generated during the current game"
        )

    # Unknown

    return (
        "unknown",
        False,
        False,
        "review",
        "Could not be confidently classified automatically"
    )

# Build classification table

records = []

for column in df.columns:

    (
        category,
        predictive_safe,
        target_candidate,
        leakage_risk,
        reason
    ) = classify_feature(column)

    records.append({
        "column": column,
        "category": category,
        "predictive_safe": predictive_safe,
        "target_candidate": target_candidate,
        "leakage_risk": leakage_risk,
        "reason": reason,
        "notes": "",
    })


feature_df = pd.DataFrame(records)

# Save classification

output_path = Path(OUTPUT_PATH)
output_path.parent.mkdir(parents=True, exist_ok=True)

feature_df.to_csv(output_path, index=False)

# Print summary

print("\n" + "=" * 60)
print("FEATURE CLASSIFICATION COMPLETE")
print("=" * 60)

print(f"\nSaved to:")
print(f"  {OUTPUT_PATH}")

print(f"\nTotal columns classified: {len(feature_df)}")

# Category counts

print("\n" + "-" * 60)
print("CATEGORY COUNTS")
print("-" * 60)

category_counts = (
    feature_df["category"]
    .value_counts()
    .sort_index()
)

print(category_counts)

# Predictive-safe counts

print("\n" + "-" * 60)
print("PREGAME PREDICTIVE SAFETY")
print("-" * 60)

safe_count = feature_df["predictive_safe"].sum()
unsafe_count = (~feature_df["predictive_safe"]).sum()

print(f"Predictive-safe:     {safe_count}")
print(f"Not predictive-safe: {unsafe_count}")

# Target candidates

print("\n" + "-" * 60)
print("TARGET CANDIDATES")
print("-" * 60)

target_candidates = feature_df[
    feature_df["target_candidate"]
]["column"]

if len(target_candidates) == 0:
    print("None")

else:
    for column in target_candidates:
        print(f"  {column}")

# Current-game features

print("\n" + "-" * 60)
print("CURRENT-GAME FEATURES")
print("-" * 60)

current_game = feature_df[
    feature_df["category"] == "current_game"
]["column"]

if len(current_game) == 0:
    print("None")

else:
    for column in current_game:
        print(f"  {column}")

# Unknown features

print("\n" + "-" * 60)
print("UNKNOWN FEATURES REQUIRING REVIEW")
print("-" * 60)

unknown = feature_df[
    feature_df["category"] == "unknown"
]["column"]

if len(unknown) == 0:

    print("None")

else:

    print(f"\n{len(unknown)} unknown columns:\n")

    for column in unknown:
        print(f"  {column}")

# Predictive-safe features

print("\n" + "-" * 60)
print("PREDICTIVE-SAFE FEATURES")
print("-" * 60)

safe_features = feature_df[
    feature_df["predictive_safe"]
]["column"]

for column in safe_features:
    print(f"  {column}")


print("\n" + "=" * 60)
print("END")
print("=" * 60)