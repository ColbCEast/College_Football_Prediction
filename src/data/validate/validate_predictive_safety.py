# SUSPICIOUS NAME CHECK
# ============================================================================

def validate_safe_feature_names(classification):
    """
    Scan all predictive-safe features for names that strongly suggest
    leakage.

    This is a secondary heuristic check. It intentionally reports
    suspicious features rather than automatically declaring every one
    invalid.
    """

    print_header("SCANNING PREDICTIVE-SAFE FEATURES FOR SUSPICIOUS NAMES")

    safe = classification[
        classification["predictive_safe"] == True
    ]

    suspicious = []

    for _, row in safe.iterrows():

        column = row["column"]
        category = row["category"]

        # Explicit postgame indicators
        if contains_any_pattern(column, POSTGAME_PATTERNS):

            suspicious.append(
                (
                    column,
                    category,
                    "postgame indicator"
                )
            )

            continue

        # Current-game/statistical indicators
        #
        # Only flag these when they are NOT clearly pregame.
        if (
            contains_any_pattern(column, CURRENT_GAME_PATTERNS)
            and not contains_any_pattern(
                column,
                SAFE_PREGAME_PATTERNS
            )
        ):
            suspicious.append(
                (
                    column,
                    category,
                    "possible current-game statistic"
                )
            )

    print(
        f"Predictive-safe features requiring manual name review:"
        f" {len(suspicious)}"
    )

    if suspicious:

        print()
        print("SUSPICIOUS FEATURES:")

        for column, category, reason in sorted(suspicious):
            print(
                f"  {column}"
                f" | category={category}"
                f" | reason={reason}"
            )

        print()
        print(
            "These are not automatically declared invalid. "
            "Review them before modeling."
        )

    else:
        print(
            "PASS: No suspicious predictive-safe feature names detected."
        )

    return suspicious


