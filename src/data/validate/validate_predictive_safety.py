"""
validate_predictive_safety.py

Validates that features marked as predictive-safe in the final feature
classification are actually safe to use for true pregame prediction.

This validator checks:

1. Classification file structure
2. Every final feature has a classification
3. Predictive-safe features are not obvious targets
4. Predictive-safe features are not obvious postgame/current-game statistics
5. Predictive-safe features do not contain suspicious leakage indicators
6. Pregame features have expected naming patterns
7. Target candidates are never predictive-safe
8. Identifiers/metadata are not accidentally marked predictive-safe
9. Produces a detailed summary of safe/unsafe features

IMPORTANT:
This script is intentionally conservative. A flagged feature does not
necessarily mean the feature is wrong; it means the feature requires
manual review before modeling.
"""

from pathlib import Path
import sys
import pandas as pd


# ============================================================================
# PATHS
# ============================================================================

PROJECT_ROOT = Path(__file__).resolve().parents[3]

CLASSIFICATION_PATH = PROJECT_ROOT / "data" / "metadata" / "final_feature_classification.csv"

FINAL_FEATURE_DIR = (
    PROJECT_ROOT
    / "data"
    / "processed"
    / "final_features"
)

YEARS = list(range(2015, 2026))


# ============================================================================
# EXPECTED CLASSIFICATION VALUES
# ============================================================================

EXPECTED_CATEGORIES = {
    "current_game",
    "identifier",
    "metadata",
    "pregame",
    "rolling_pregame",
    "static_pregame",
    "target_candidate",
}


# ============================================================================
# OBVIOUSLY UNSAFE FEATURE PATTERNS
# ============================================================================

# These patterns strongly indicate that a feature contains information
# generated by the game itself or after the game was completed.

POSTGAME_PATTERNS = [
    "postgame",
    "post_game",
    "postGame",
]

CURRENT_GAME_PATTERNS = [
    # Raw game statistics
    "_home",
    "_away",

    # Explicit game-level statistics
    "points",
    "yards",
    "touchdowns",
    "turnovers",
    "interceptions",
    "completions",
    "attempts",
    "rushing",
    "passing",
    "sacks",
    "tackles",
    "penalties",
    "fumbles",
    "possession",
    "firstdowns",
    "firstDowns",
    "thirdDown",
    "fourthDown",

    # Results
    "win",
    "loss",
    "score",
    "pointDifferential",
]

TARGET_PATTERNS = [
    "win",
    "points",
    "pointDifferential",
    "pointsFor",
    "pointsAgainst",
]


# ============================================================================
# SAFE PREGAME PATTERNS
# ============================================================================

SAFE_PREGAME_PATTERNS = [
    "Before",
    "AvgBefore",
    "Last3",
    "Last5",
    "Pregame",
    "pregame",
    "Elo",
    "elo",
]


# ============================================================================
# HELPER FUNCTIONS
# ============================================================================

def print_header(title):
    print()
    print("=" * 70)
    print(title)
    print("=" * 70)


def load_classification():
    """Load final feature classification."""

    print_header("LOADING FINAL FEATURE CLASSIFICATION")

    if not CLASSIFICATION_PATH.exists():
        raise FileNotFoundError(
            f"Could not find final feature classification:\n"
            f"  {CLASSIFICATION_PATH}\n\n"
            f"Run create_final_feature_classification.py first."
        )

    classification = pd.read_csv(CLASSIFICATION_PATH)

    print(f"Loaded classification:")
    print(f"  Rows:    {len(classification)}")
    print(f"  Columns: {len(classification.columns)}")

    return classification


def load_final_features():
    """Load one final feature file from each season."""

    print_header("LOADING FINAL FEATURE DATA")

    final_features = {}

    for year in YEARS:

        path = FINAL_FEATURE_DIR / f"final_features_{year}.csv"

        if not path.exists():
            raise FileNotFoundError(
                f"Could not find final feature file for {year}:\n"
                f"  {path}"
            )

        df = pd.read_csv(path)

        final_features[year] = df

        print(
            f"{year}: "
            f"{len(df.columns)} columns, "
            f"{len(df)} rows"
        )

    return final_features


def validate_classification_structure(classification):
    """Validate classification file structure."""

    print_header("VALIDATING CLASSIFICATION STRUCTURE")

    required_columns = {
        "column",
        "category",
        "predictive_safe",
    }

    missing = required_columns - set(classification.columns)

    if missing:
        print("FAIL: Missing required classification columns:")
        for column in sorted(missing):
            print(f"  {column}")
        return False

    print("PASS: Required classification columns are present.")

    duplicates = classification["column"].duplicated().sum()

    print()
    print(f"Duplicate classified feature names: {duplicates}")

    if duplicates:
        print("FAIL: Duplicate feature names detected.")
        return False

    print("PASS: No duplicate classified feature names.")

    missing_categories = classification["category"].isna().sum()

    print()
    print(f"Missing feature categories: {missing_categories}")

    if missing_categories:
        print("FAIL: Some features have no category.")
        return False

    print("PASS: Every feature has a category.")

    missing_safe = classification["predictive_safe"].isna().sum()

    print()
    print(f"Missing predictive-safe flags: {missing_safe}")

    if missing_safe:
        print("FAIL: Some features have no predictive-safe flag.")
        return False

    print("PASS: Every feature has a predictive-safe flag.")

    invalid_categories = sorted(
        set(classification["category"])
        - EXPECTED_CATEGORIES
    )

    if invalid_categories:
        print()
        print("FAIL: Invalid feature categories:")
        for category in invalid_categories:
            print(f"  {category}")
        return False

    print("PASS: All feature categories are recognized.")

    return True


def normalize_predictive_safe(classification):
    """
    Convert predictive_safe values to actual booleans.

    Handles CSV representations such as:
        True
        False
        TRUE
        FALSE
        1
        0
    """

    classification = classification.copy()

    classification["predictive_safe"] = (
        classification["predictive_safe"]
        .astype(str)
        .str.strip()
        .str.lower()
        .map({
            "true": True,
            "false": False,
            "1": True,
            "0": False,
        })
    )

    return classification


def get_final_columns(final_features):
    """Get the common final feature schema."""

    schemas = {}

    for year, df in final_features.items():
        schemas[year] = set(df.columns)

    reference_year = YEARS[0]
    reference_columns = schemas[reference_year]

    return reference_columns, schemas


def validate_final_schema(final_features):
    """Validate that all seasons have identical columns."""

    print_header("VALIDATING FINAL FEATURE SCHEMA")

    reference_year = YEARS[0]
    reference_columns = set(final_features[reference_year].columns)

    print(f"Reference season: {reference_year}")
    print(f"Reference columns: {len(reference_columns)}")

    all_pass = True

    for year in YEARS:

        columns = set(final_features[year].columns)

        missing = reference_columns - columns
        extra = columns - reference_columns

        print()
        print(f"{year}:")
        print(f"  Columns: {len(columns)}")
        print(f"  Missing vs {reference_year}: {len(missing)}")
        print(f"  Extra vs {reference_year}: {len(extra)}")

        if missing or extra:
            all_pass = False

    if all_pass:
        print()
        print("PASS: All final feature datasets have identical schemas.")
    else:
        print()
        print("FAIL: Final feature schemas differ.")

    return all_pass


def validate_classification_coverage(
    classification,
    final_features,
):
    """Ensure classification exactly covers the final feature schema."""

    print_header("VALIDATING CLASSIFICATION COVERAGE")

    reference_columns = set(final_features[YEARS[0]].columns)
    classified_columns = set(classification["column"])

    unclassified = reference_columns - classified_columns
    missing_from_final = classified_columns - reference_columns

    print(f"Final feature columns:")
    print(f"  {len(reference_columns)}")

    print()
    print(f"Classified feature columns:")
    print(f"  {len(classified_columns)}")

    print()
    print(f"Unclassified final feature columns:")
    print(f"  {len(unclassified)}")

    if unclassified:
        print()
        print("UNCLASSIFIED:")
        for column in sorted(unclassified):
            print(f"  {column}")

    print()
    print(f"Classified columns not present in final features:")
    print(f"  {len(missing_from_final)}")

    if missing_from_final:
        print()
        print("CLASSIFIED BUT NOT IN FINAL DATA:")
        for column in sorted(missing_from_final):
            print(f"  {column}")

    if unclassified or missing_from_final:
        print()
        print("FAIL: Classification coverage is inconsistent.")
        return False

    print()
    print("PASS: Classification exactly matches final feature schema.")

    return True


