# LEAKAGE CHECKS
# ============================================================================

def contains_any_pattern(column, patterns):
    """Case-insensitive substring matching."""

    column_lower = column.lower()

    return any(
        pattern.lower() in column_lower
        for pattern in patterns
    )


def validate_postgame_features(classification):
    """Ensure obvious postgame features are never predictive-safe."""

    print_header("VALIDATING POSTGAME FEATURES")

    safe = classification[
        classification["predictive_safe"] == True
    ]

    suspicious = []

    for _, row in safe.iterrows():

        column = row["column"]

        if contains_any_pattern(column, POSTGAME_PATTERNS):
            suspicious.append(column)

    print(f"Predictive-safe features containing postgame indicators:")
    print(f"  {len(suspicious)}")

    if suspicious:
        print()
        print("FAIL: Postgame features marked predictive-safe:")

        for column in sorted(suspicious):
            print(f"  {column}")

        return False

    print("PASS: No obvious postgame features are predictive-safe.")

    return True


def validate_target_features(classification):
    """Ensure target candidates are never predictive-safe."""

    print_header("VALIDATING TARGET FEATURES")

    target_candidates = classification[
        classification["category"] == "target_candidate"
    ]

    unsafe_targets = target_candidates[
        target_candidates["predictive_safe"] == True
    ]

    print(f"Target candidate features: {len(target_candidates)}")
    print(
        f"Target candidates marked predictive-safe: "
        f"{len(unsafe_targets)}"
    )

    if len(unsafe_targets) > 0:

        print()
        print("FAIL: Target candidates marked predictive-safe:")

        for column in sorted(unsafe_targets["column"]):
            print(f"  {column}")

        return False

    print("PASS: No target candidates are predictive-safe.")

    return True


def validate_current_game_features(classification):
    """
    Current-game features should not be predictive-safe for a true
    pregame prediction model.
    """

    print_header("VALIDATING CURRENT-GAME FEATURES")

    current_game = classification[
        classification["category"] == "current_game"
    ]

    safe_current_game = current_game[
        current_game["predictive_safe"] == True
    ]

    print(f"Current-game features: {len(current_game)}")
    print(
        f"Current-game features marked predictive-safe: "
        f"{len(safe_current_game)}"
    )

    if len(safe_current_game) > 0:

        print()
        print("FAIL: Current-game features marked predictive-safe:")

        for column in sorted(safe_current_game["column"]):
            print(f"  {column}")

        return False

    print("PASS: No current-game features are predictive-safe.")

    return True


def validate_identifiers(classification):
    """Identifiers should not be predictive model inputs by default."""

    print_header("VALIDATING IDENTIFIER FEATURES")

    identifiers = classification[
        classification["category"] == "identifier"
    ]

    safe_identifiers = identifiers[
        identifiers["predictive_safe"] == True
    ]

    print(f"Identifier features: {len(identifiers)}")
    print(
        f"Identifiers marked predictive-safe: "
        f"{len(safe_identifiers)}"
    )

    if len(safe_identifiers) > 0:

        print()
        print("WARNING: Identifier features marked predictive-safe:")

        for column in sorted(safe_identifiers["column"]):
            print(f"  {column}")

        print()
        print(
            "These should normally be excluded from model inputs, "
            "even if technically available before kickoff."
        )

        return False

    print("PASS: No identifiers are predictive-safe.")

    return True


def validate_metadata(classification):
    """
    Metadata can be useful, but for the base pregame model we conservatively
    require metadata to be explicitly marked unsafe.
    """

    print_header("VALIDATING METADATA FEATURES")

    metadata = classification[
        classification["category"] == "metadata"
    ]

    safe_metadata = metadata[
        metadata["predictive_safe"] == True
    ]

    print(f"Metadata features: {len(metadata)}")
    print(
        f"Metadata marked predictive-safe: "
        f"{len(safe_metadata)}"
    )

    if len(safe_metadata) > 0:

        print()
        print(
            "WARNING: Metadata features marked predictive-safe:"
        )

        for column in sorted(safe_metadata["column"]):
            print(f"  {column}")

        print()
        print(
            "Review these manually. Metadata such as venue, conference, "
            "neutral-site status, or kickoff information can potentially "
            "be legitimate pregame predictors."
        )

        return False

    print(
        "PASS: No metadata features are marked predictive-safe."
    )

    return True


