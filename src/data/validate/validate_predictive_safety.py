# SUMMARY
# ============================================================================

def print_feature_summary(classification):
    """Print useful summary of the final classification."""

    print_header("PREDICTIVE-SAFETY SUMMARY")

    safe = classification[
        classification["predictive_safe"] == True
    ]

    unsafe = classification[
        classification["predictive_safe"] == False
    ]

    print(f"Total features:        {len(classification)}")
    print(f"Predictive-safe:       {len(safe)}")
    print(f"Not predictive-safe:   {len(unsafe)}")

    print()
    print("BY CATEGORY:")
    print()

    summary = (
        classification
        .groupby(["category", "predictive_safe"])
        .size()
        .unstack(fill_value=0)
    )

    for category in sorted(summary.index):

        safe_count = summary.loc[category].get(True, 0)
        unsafe_count = summary.loc[category].get(False, 0)

        print(
            f"  {category:<20}"
            f" safe={safe_count:<4}"
            f" unsafe={unsafe_count:<4}"
        )

    print()
    print("PREDICTIVE-SAFE FEATURES:")

    for category in [
        "pregame",
        "rolling_pregame",
        "static_pregame",
        "metadata",
        "identifier",
        "current_game",
        "target_candidate",
    ]:

        features = classification[
            (classification["category"] == category)
            & (classification["predictive_safe"] == True)
        ]["column"].tolist()

        if not features:
            continue

        print()
        print(f"  {category} ({len(features)}):")

        for column in sorted(features):
            print(f"    {column}")


# ============================================================================
# MAIN
# ============================================================================

def main():

    print()
    print("=" * 70)
    print("VALIDATING PREDICTIVE SAFETY")
    print("=" * 70)
    print()
    print(
        "This script validates that features marked predictive-safe "
        "are appropriate for true pregame prediction."
    )

    all_pass = True

    # ------------------------------------------------------------------------
    # Load data
    # ------------------------------------------------------------------------

    classification = load_classification()
    final_features = load_final_features()

    # ------------------------------------------------------------------------
    # Normalize boolean values
    # ------------------------------------------------------------------------

    classification = normalize_predictive_safe(classification)

    # Check whether conversion introduced missing values.
    if classification["predictive_safe"].isna().any():

        print()
        print(
            "FAIL: Some predictive_safe values could not be interpreted "
            "as True/False."
        )

        print(
            classification[
                classification["predictive_safe"].isna()
            ][["column", "predictive_safe"]]
        )

        sys.exit(1)

    # ------------------------------------------------------------------------
    # Structural validation
    # ------------------------------------------------------------------------

    if not validate_classification_structure(classification):
        all_pass = False

    # ------------------------------------------------------------------------
    # Final feature schema
    # ------------------------------------------------------------------------

    if not validate_final_schema(final_features):
        all_pass = False

    # ------------------------------------------------------------------------
    # Classification coverage
    # ------------------------------------------------------------------------

    if not validate_classification_coverage(
        classification,
        final_features,
    ):
        all_pass = False

    # ------------------------------------------------------------------------
    # Leakage checks
    # ------------------------------------------------------------------------

    if not validate_postgame_features(classification):
        all_pass = False

    if not validate_target_features(classification):
        all_pass = False

    if not validate_current_game_features(classification):
        all_pass = False

    if not validate_identifiers(classification):
        all_pass = False

    if not validate_metadata(classification):
        all_pass = False

    if not validate_category_safety_consistency(
        classification
    ):
        all_pass = False

    # ------------------------------------------------------------------------
    # Suspicious-name scan
    # ------------------------------------------------------------------------

    suspicious = validate_safe_feature_names(classification)

    # Suspicious features do not automatically fail the validator.
    # They require human review.

    # ------------------------------------------------------------------------
    # Summary
    # ------------------------------------------------------------------------

    print_feature_summary(classification)

    # ------------------------------------------------------------------------
    # Final result
    # ------------------------------------------------------------------------

    print_header("FINAL VALIDATION RESULT")

    if all_pass:

        if suspicious:

            print(
                "PASS WITH MANUAL REVIEW:"
            )

            print()
            print(
                "No hard predictive-safety violations were detected."
            )

            print(
                f"However, {len(suspicious)} predictive-safe features "
                "have names that should be manually reviewed."
            )

            print()
            print(
                "Do NOT proceed to modeling until those features "
                "have been reviewed."
            )

        else:

            print(
                "PASS: Predictive safety validation completed successfully."
            )

            print()
            print(
                "No obvious leakage or category/safety violations "
                "were detected."
            )

    else:

        print(
            "FAIL: Predictive safety validation requires investigation."
        )

        print()
        print(
            "Do NOT proceed to modeling until the predictive-safety "
            "violations have been resolved."
        )

        sys.exit(1)


if __name__ == "__main__":
    main()