# CATEGORY / SAFETY CONSISTENCY
# ============================================================================

def validate_category_safety_consistency(classification):
    """Validate logical relationships between category and safety flag."""

    print_header("VALIDATING CATEGORY / SAFETY CONSISTENCY")

    failures = []

    # Target candidates must never be safe.
    invalid = classification[
        (classification["category"] == "target_candidate")
        & (classification["predictive_safe"] == True)
    ]

    for _, row in invalid.iterrows():
        failures.append(
            (
                row["column"],
                row["category"],
                "target_candidate cannot be predictive-safe",
            )
        )

    # Current-game features must never be safe for pregame modeling.
    invalid = classification[
        (classification["category"] == "current_game")
        & (classification["predictive_safe"] == True)
    ]

    for _, row in invalid.iterrows():
        failures.append(
            (
                row["column"],
                row["category"],
                "current_game cannot be predictive-safe",
            )
        )

    # Identifiers should not be model inputs.
    invalid = classification[
        (classification["category"] == "identifier")
        & (classification["predictive_safe"] == True)
    ]

    for _, row in invalid.iterrows():
        failures.append(
            (
                row["column"],
                row["category"],
                "identifier should not be predictive-safe",
            )
        )

    print(f"Category/safety violations: {len(failures)}")

    if failures:

        print()
        print("VIOLATIONS:")

        for column, category, reason in failures:
            print(
                f"  {column}"
                f" | category={category}"
                f" | {reason}"
            )

        return False

    print("PASS: Category and predictive-safety assignments are consistent.")

    return True


